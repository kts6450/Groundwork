def _clean(value: object) -> str | None:
    if value is None or not isinstance(value, str):
        return None
    text = value.strip()
    return text or None


def map_license(business_type: object) -> str | None:
    """인허가 업태구분명 → 묶음. 없으면 None."""
    key = _clean(business_type)
    if key is None:
        return None
    return LICENSE_MAP.get(key)


